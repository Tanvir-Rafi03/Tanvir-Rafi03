CH_W, CH_H, CH_GAP = 5, 7, 1


def text_w(s, px=3):
    """Pixel width of a rendered string."""
    return len(s) * (CH_W + CH_GAP) * px - CH_GAP * px


def text(s, x, y, px=3, fill=TXT, shadow=True, sh=None, anchor="start"):
    """Bitmap text as merged rects. y is the TOP of the glyph box."""
    s = str(s).upper()
    total = text_w(s, px)
    if anchor == "middle": x -= total / 2
    elif anchor == "end":  x -= total
    out = []
    for pas in ((1, 0) if shadow else (0,)):
        col = (sh or TXT_SH) if pas else fill
        off = px if pas else 0
        cx = x
        for ch in s:
            g = F.get(ch, F["?"])
            for r, row in enumerate(g):
                c = 0
                while c < CH_W:
                    if row[c] == "1":
                        run = 1
                        while c + run < CH_W and row[c + run] == "1":
                            run += 1
                        out.append(f'<rect x="{cx+c*px+off:.0f}" y="{y+r*px+off:.0f}" '
                                   f'width="{run*px:.0f}" height="{px:.0f}" fill="{col}"/>')
                        c += run
                    else:
                        c += 1
            cx += (CH_W + CH_GAP) * px
    return "".join(out)


def bevel(x, y, w, h, face=GUI, lt=GUI_LT, dk=GUI_DK, t=3):
    """Classic Minecraft GUI bevel: light top/left, dark bottom/right."""
    return (f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{face}"/>'
            f'<rect x="{x}" y="{y}" width="{w}" height="{t}" fill="{lt}"/>'
            f'<rect x="{x}" y="{y}" width="{t}" height="{h}" fill="{lt}"/>'
            f'<rect x="{x}" y="{y+h-t}" width="{w}" height="{t}" fill="{dk}"/>'
            f'<rect x="{x+w-t}" y="{y}" width="{t}" height="{h}" fill="{dk}"/>')


def slot(x, y, s=54):
    """Inventory slot: sunken bevel (dark top/left, light bottom/right)."""
    return bevel(x, y, s, s, SLOT, SLOT_DK, SLOT_LT, 3)


def block(x, y, s, top, side, spec=None):
    """A pixel block with a lighter cap and a couple of texture notches."""
    q = max(3, s // 5)
    o = (f'<rect x="{x}" y="{y}" width="{s}" height="{s}" fill="{side}"/>'
         f'<rect x="{x}" y="{y}" width="{s}" height="{max(2,s//4)}" fill="{top}"/>')
    if spec:
        o += (f'<rect x="{x+q*0.6:.0f}" y="{y+s-2.2*q:.0f}" width="{q*1.4:.0f}" height="{q*1.2:.0f}" fill="{spec}"/>'
              f'<rect x="{x+s-2.1*q:.0f}" y="{y+q*0.9:.0f}" width="{q*1.3:.0f}" height="{q*1.3:.0f}" fill="{spec}"/>'
              f'<rect x="{x+s*0.42:.0f}" y="{y+s*0.46:.0f}" width="{q:.0f}" height="{q:.0f}" fill="{spec}"/>')
    return o


def heart(x, y, s=4, full=True):
    """8x8 pixel heart."""
    pat = ["00110110","01111111","01111111","01111111","00111110","00011100","00001000","00000000"]
    col = RED if full else "#4b4b4b"
    out = [f'<rect x="{x}" y="{y}" width="{s*8}" height="{s*8}" fill="#0000" />']
    for r, row in enumerate(pat):
        c = 0
        while c < 8:
            if row[c] == "1":
                run = 1
                while c+run < 8 and row[c+run] == "1": run += 1
                out.append(f'<rect x="{x+c*s}" y="{y+r*s}" width="{run*s}" height="{s}" fill="{col}"/>')
                c += run
            else: c += 1
    return "".join(out)
